// Generates Web/icons.js from Lucide's SVG sources, so Studio ships only the icons it uses and
// never loads anything from a CDN (docs/UNIFIED-UI.md section 6).
//   npm pack lucide-static@1.54.0 && tar -xzf lucide-static-1.54.0.tgz
//   node tools/gen-icons.mjs package/icons
// The output is committed; re-run only when the icon list changes. Node is a development tool
// here, never needed on the workstation that runs Bowerbird.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const LUCIDE_VERSION = '1.54.0';
// Bowerbird's icon name -> Lucide icon name.
const ICONS = {
  explorer: 'folder-tree',
  search: 'search',
  insights: 'chart-column',
  duplicates: 'copy',
  organize: 'folders',
  rename: 'pencil-line',
  code: 'code-xml',
  assistant: 'sparkles',
  diagnostics: 'stethoscope',
  power: 'power',
  keyboard: 'keyboard',
  themeSystem: 'sun-moon',
  themeLight: 'sun',
  themeDark: 'moon',
  collapse: 'panel-left-close',
  expand: 'panel-left-open',
  settings: 'settings',
  refresh: 'refresh-cw',
  index: 'scan-search',
  browse: 'folder-search',
  up: 'arrow-up',
  folder: 'folder',
  file: 'file',
  triage: 'layout-grid',
  audit: 'shield-check',
  record: 'circle',
  stop: 'square',
  flag: 'flag',
  check: 'check',
  minus: 'minus',
  close: 'x',
};
// Icons drawn filled rather than outlined.
const FILLED = new Set(['record', 'stop']);

// Shared fleet comment scan. Keep these three functions identical across icon generators.
function commentEnd(s, from) {
  for (let j = from; j < s.length - 2; j++) {
    if (s[j] !== '-' || s[j + 1] !== '-') continue;
    if (s[j + 2] === '>') return j + 3;
    if (s[j + 2] === '!' && s[j + 3] === '>') return j + 4;
  }
  return -1;
}
function stripOnce(s) {
  let out = '';
  let i = 0;
  while (i < s.length) {
    const start = s.indexOf('<!--', i);
    if (start < 0) return out + s.slice(i);
    out += s.slice(i, start);
    if (s[start + 4] === '>') { i = start + 5; continue; }
    if (s[start + 4] === '-' && s[start + 5] === '>') { i = start + 6; continue; }
    const end = commentEnd(s, start + 4);
    if (end < 0) return out;
    i = end;
  }
  return out;
}
export function stripHtmlComments(input) {
  let cur = String(input);
  let prev;
  do { prev = cur; cur = stripOnce(cur); } while (cur !== prev);
  return cur;
}

export function shapesFromSvg(svg) {
  const body = stripHtmlComments(svg)
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '');
  return [...body.matchAll(/<([a-z]+)\s+([^>]*?)\s*\/>/g)].map(([, tag, attrs]) => [
    tag,
    Object.fromEntries([...attrs.matchAll(/([a-z-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v])),
  ]);
}

function runningAsScript() {
  const entry = process.argv[1];
  if (!entry) return false;
  return import.meta.url === pathToFileURL(path.resolve(entry)).href;
}

if (runningAsScript()) {
  const dir = process.argv[2];
  if (!dir) {
    console.error('usage: node tools/gen-icons.mjs <lucide-static>/icons');
    process.exit(1);
  }
  const shapes = {};
  for (const [name, lucide] of Object.entries(ICONS)) {
    shapes[name] = shapesFromSvg(readFileSync(path.join(dir, `${lucide}.svg`), 'utf8'));
    if (!shapes[name].length) throw Error(`No shapes parsed from ${lucide}.svg`);
  }

  const lines = Object.entries(shapes).map(([name, list]) => `  ${name}: ${JSON.stringify(list)}, // ${ICONS[name]}`);
  const out = `// GENERATED by tools/gen-icons.mjs from Lucide ${LUCIDE_VERSION} (ISC licence, https://lucide.dev). Do not edit.
// Drawn at 16 px in controls and 20 px in navigation, 1.75 px stroke, currentColor (docs/UNIFIED-UI.md section 6).
// Markup uses <span data-icon="name"></span> (data-icon-size="20" in navigation); hydrate() swaps each
// placeholder for an inline SVG built with DOM calls, so the strict CSP needs no inline markup.
'use strict';
(function(root){
 const SHAPES={
${lines.join('\n')}
 };
 const FILLED=new Set(${JSON.stringify([...FILLED])});
 const NS='http://www.w3.org/2000/svg';
 function icon(name,size){
  const shapes=SHAPES[name];if(!shapes)return null;
  const svg=root.document.createElementNS(NS,'svg');
  const px=String(size||16);
  for(const [k,v] of [['width',px],['height',px],['viewBox','0 0 24 24'],['fill',FILLED.has(name)?'currentColor':'none'],['stroke','currentColor'],['stroke-width','1.75'],['stroke-linecap','round'],['stroke-linejoin','round'],['aria-hidden','true'],['focusable','false'],['class','icon'],['data-icon-name',name]])svg.setAttribute(k,v);
  for(const [tag,attrs] of shapes){const child=root.document.createElementNS(NS,tag);for(const k of Object.keys(attrs))child.setAttribute(k,attrs[k]);svg.append(child)}
  return svg;
 }
 function hydrate(scope){
  for(const slot of (scope||root.document).querySelectorAll('span[data-icon]')){
   const svg=icon(slot.dataset.icon,Number(slot.dataset.iconSize)||16);
   if(svg)slot.replaceWith(svg);
  }
 }
 root.BowerbirdIcons={icon,hydrate,names:Object.keys(SHAPES)};
 if(root.document.readyState==='loading')root.document.addEventListener('DOMContentLoaded',()=>hydrate());
 else hydrate();
})(window);
`;
  const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'Web', 'icons.js');
  writeFileSync(target, out);
  console.log(`wrote ${lines.length} icons to ${target}`);
}
